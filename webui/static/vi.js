  const entries = Object.entries(phrases).sort((a, b) => b[0].length - a[0].length);
  const containsHan = (value) => /[\u3400-\u9fff]/.test(value || '');

  function translate(value) {
    if (!containsHan(value)) return value;
    let result = value;
    for (let pass = 0; pass < 3 && containsHan(result); pass += 1) {
      const before = result;
      for (const [source, target] of entries) result = result.split(source).join(target);
      if (result === before) break;
    }
    return result;
  }

  window.__translateVi = translate;

  function translateElement(element) {
    if (!(element instanceof Element)) return;
    for (const attr of ['title', 'placeholder', 'aria-label']) {
      const value = element.getAttribute(attr);
      if (value && containsHan(value)) {
        const translated = translate(value);
        if (translated !== value) element.setAttribute(attr, translated);
      }
    }
  }

  function shouldSkipTextNode(node) {
    const parent = node.parentElement;
    return !parent || parent.matches('script, style, code, pre, textarea');
  }

  function translateTree(root) {
    if (root instanceof Element) translateElement(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) {
        if (!shouldSkipTextNode(node) && containsHan(node.nodeValue)) node.nodeValue = translate(node.nodeValue);
      } else {
        translateElement(node);
      }
      node = walker.nextNode();
    }
  }

